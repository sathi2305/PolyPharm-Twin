/**
 * Validates a user-inputted dosage against clinical safety guidelines
 */
export function validateDosageSafety(
  drug: { id: string; genericName: string },
  doseMg: number,
  patientContext?: PatientContext
): DosageValidationResult {
  const key = drug.id.toLowerCase();
  const guideline = DOSAGE_SAFETY_GUIDELINES[key];

  // Generic fallback if drug is not in explicit guideline table
  if (!guideline) {
    const estimatedStandard = 50; // fallback standard
    const estimatedMax = 150;     // 3x standard
    const isExceeded = doseMg > estimatedMax;
    const isHigh = doseMg > estimatedStandard * 1.8;

    return {
      status: isExceeded ? 'critical' : isHigh ? 'warning' : 'safe',
      currentDoseMg: doseMg,
      maxRecommendedDoseMg: estimatedMax,
      standardDoseMg: estimatedStandard,
      unit: 'mg',
      isMaxExceeded: isExceeded,
      isHighDoseWarning: isHigh,
      isSubtherapeutic: doseMg < estimatedStandard * 0.2,
      warningMessage: isExceeded
        ? `Dosage of ${doseMg} mg exceeds typical recommended clinical range (${estimatedMax} mg max).`
        : isHigh
        ? `Dosage of ${doseMg} mg is higher than typical clinical baseline (${estimatedStandard} mg).`
        : 'Dosage is within standard exploratory parameters.',
      guidelineSource: 'Estimated Conservative Standard',
    };
  }

  // Determine patient-specific maximum safe daily dose factoring renal & age status
  let effectiveMaxDose = guideline.maxDailyDoseMg;
  let patientRiskModifier = '';

  if (
    patientContext?.renalFunctionEgfr !== undefined &&
    guideline.renalAdjustmentEgfrThreshold !== undefined &&
    guideline.renalAdjustedMaxDoseMg !== undefined &&
    patientContext.renalFunctionEgfr < guideline.renalAdjustmentEgfrThreshold
  ) {
    effectiveMaxDose = guideline.renalAdjustedMaxDoseMg;
    patientRiskModifier = ` (Renal-adjusted max: ${guideline.renalAdjustedMaxDoseMg} mg due to eGFR ${patientContext.renalFunctionEgfr} mL/min)`;
  } else if (
    patientContext?.age !== undefined &&
    patientContext.age >= 65 &&
    guideline.elderlyMaxDoseMg !== undefined
  ) {
    effectiveMaxDose = guideline.elderlyMaxDoseMg;
    patientRiskModifier = ` (Geriatric-adjusted max: ${guideline.elderlyMaxDoseMg} mg for age ${patientContext.age})`;
  }

  const isMaxExceeded = doseMg > effectiveMaxDose;
  const isHighDose = !isMaxExceeded && doseMg > guideline.warningThresholdMg;
  const isSubtherapeutic = doseMg > 0 && doseMg < guideline.minEffectiveDoseMg;

  if (isMaxExceeded) {
    return {
      status: 'critical',
      currentDoseMg: doseMg,
      maxRecommendedDoseMg: effectiveMaxDose,
      standardDoseMg: guideline.standardDoseMg,
      unit: guideline.unit,
      isMaxExceeded: true,
      isHighDoseWarning: true,
      isSubtherapeutic: false,
      warningMessage: `CRITICAL SAFETY ALERT: Inputted dose of ${doseMg} ${guideline.unit} EXCEEDS maximum daily safety limit of ${effectiveMaxDose} ${guideline.unit}${patientRiskModifier}!`,
      clinicalRisk: guideline.safetyWarning,
      toxicitySigns: guideline.toxicityManifestations,
      recommendation: `Reduce dosage to ≤ ${effectiveMaxDose} ${guideline.unit} (standard clinical dose: ${guideline.standardDoseMg} ${guideline.unit}) to prevent toxicity.`,
      guidelineSource: guideline.guidelineSource,
    };
  }

  if (isHighDose) {
    return {
      status: 'warning',
      currentDoseMg: doseMg,
      maxRecommendedDoseMg: effectiveMaxDose,
      standardDoseMg: guideline.standardDoseMg,
      unit: guideline.unit,
      isMaxExceeded: false,
      isHighDoseWarning: true,
      isSubtherapeutic: false,
      warningMessage: `HIGH DOSE WARNING: ${doseMg} ${guideline.unit} is elevated above typical clinical starting range (${guideline.standardDoseMg} ${guideline.unit}). Max safe limit is ${effectiveMaxDose} ${guideline.unit}${patientRiskModifier}.`,
      clinicalRisk: guideline.safetyWarning,
      toxicitySigns: guideline.toxicityManifestations,
      recommendation: `Monitor plasma concentrations and adverse effects closely. Titrate cautiously toward standard maintenance of ${guideline.standardDoseMg} ${guideline.unit}.`,
      guidelineSource: guideline.guidelineSource,
    };
  }

  if (isSubtherapeutic) {
    return {
      status: 'subtherapeutic',
      currentDoseMg: doseMg,
      maxRecommendedDoseMg: effectiveMaxDose,
      standardDoseMg: guideline.standardDoseMg,
      unit: guideline.unit,
      isMaxExceeded: false,
      isHighDoseWarning: false,
      isSubtherapeutic: true,
      warningMessage: `SUBTHERAPEUTIC WARNING: ${doseMg} ${guideline.unit} is below the Minimum Effective Dose (${guideline.minEffectiveDoseMg} ${guideline.unit}). Clinical efficacy may be compromised.`,
      recommendation: `Consider titrating to the minimum therapeutic dose of ${guideline.minEffectiveDoseMg} ${guideline.unit}.`,
      guidelineSource: guideline.guidelineSource,
    };
  }

  return {
    status: 'safe',
    currentDoseMg: doseMg,
    maxRecommendedDoseMg: effectiveMaxDose,
    standardDoseMg: guideline.standardDoseMg,
    unit: guideline.unit,
    isMaxExceeded: false,
    isHighDoseWarning: false,
    isSubtherapeutic: false,
    warningMessage: `Dosage of ${doseMg} ${guideline.unit} is within standard recommended clinical safety guidelines (${guideline.minEffectiveDoseMg} - ${effectiveMaxDose} ${guideline.unit}).`,
    guidelineSource: guideline.guidelineSource,
  };
}
