/**
 * Universal phrase translator
 * Looks up any UI string against the dictionary for the given language code.
 * Falls back to English if no translation is found.
 */
export function translatePhrase(text: string, langCode: string = 'en'): string {
  if (!text) return '';
  if (!langCode || langCode === 'en') return text;

  const entry = UI_TRANSLATIONS[text];
  if (entry && entry[langCode]) {
    return entry[langCode];
  }

  // Case-insensitive fallback lookup
  const lower = text.toLowerCase().trim();
  for (const [key, map] of Object.entries(UI_TRANSLATIONS)) {
    if (key.toLowerCase().trim() === lower) {
      if (map[langCode]) return map[langCode];
    }
  }

  return text;
}
